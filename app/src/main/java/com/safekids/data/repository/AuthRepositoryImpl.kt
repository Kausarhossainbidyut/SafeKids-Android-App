package com.safekids.data.repository

import com.safekids.core.security.PasswordHasher
import com.safekids.data.local.dao.ParentUserDao
import com.safekids.data.local.entity.ParentUserEntity
import com.safekids.data.mapper.toDomain
import com.safekids.domain.model.ParentUser
import com.safekids.domain.repository.AuthRepository
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import javax.inject.Inject
import javax.inject.Singleton

@Singleton
class AuthRepositoryImpl @Inject constructor(
    private val parentUserDao: ParentUserDao,
    private val passwordHasher: PasswordHasher
) : AuthRepository {

    private var currentUserId: Long? = null

    override suspend fun register(
        name: String,
        phone: String,
        password: String
    ): Result<ParentUser> {
        return try {
            val existing = parentUserDao.findByPhone(phone)
            if (existing != null) {
                return Result.failure(Exception("Phone already registered"))
            }

            val salt = passwordHasher.generateSalt()
            val hashedPassword = passwordHasher.hashPassword(password, salt)
            
            val user = ParentUserEntity(
                id = 0, // Auto-generated by Room
                name = name,
                phone = phone,
                passwordSalt = salt,
                passwordHash = hashedPassword,
                createdAt = System.currentTimeMillis()
            )

            val userId = parentUserDao.insert(user)
            currentUserId = userId
            
            // Fetch the inserted user to get the generated ID
            val insertedUser = parentUserDao.findById(userId)
                ?: return Result.failure(Exception("Failed to fetch inserted user"))

            Result.success(insertedUser.toDomain())
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    override suspend fun login(phone: String, password: String): Result<ParentUser> {
        return try {
            val user = parentUserDao.findByPhone(phone)
                ?: return Result.failure(Exception("User not found"))

            if (!passwordHasher.verifyPassword(password, user.passwordHash, user.passwordSalt)) {
                return Result.failure(Exception("Invalid password"))
            }

            currentUserId = user.id
            parentUserDao.updateLastLogin(user.id)
            
            Result.success(user.toDomain())
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    override suspend fun logout() {
        currentUserId = null
    }

    override fun getCurrentUser(): Flow<ParentUser?> {
        val userId = currentUserId ?: return kotlinx.coroutines.flow.flowOf(null)
        return kotlinx.coroutines.flow.flow {
            val user = parentUserDao.findById(userId)
            emit(user?.toDomain())
        }
    }

    override suspend fun isLoggedIn(): Boolean {
        return currentUserId != null
    }

    override suspend fun verifyPassword(password: String): Boolean {
        val userId = currentUserId ?: return false
        val user = parentUserDao.findById(userId) ?: return false
        return passwordHasher.verifyPassword(password, user.passwordHash, user.passwordSalt)
    }
    
    override suspend fun changePassword(
        oldPassword: String,
        newPassword: String
    ): Result<Unit> {
        return try {
            val userId = currentUserId ?: return Result.failure(Exception("Not logged in"))
            val user = parentUserDao.findById(userId) ?: return Result.failure(Exception("User not found"))
            
            if (!passwordHasher.verifyPassword(oldPassword, user.passwordHash, user.passwordSalt)) {
                return Result.failure(Exception("Invalid old password"))
            }
            
            val newSalt = passwordHasher.generateSalt()
            val newHash = passwordHasher.hashPassword(newPassword, newSalt)
            
            parentUserDao.updatePassword(userId, newSalt, newHash)
            
            Result.success(Unit)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
    
    override suspend fun generateRecoveryCodes(): List<String> {
        // Generate 10 recovery codes
        return (1..10).map {
            val chars = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
            (1..12).map { chars.random() }.joinToString("").chunked(4).joinToString("-")
        }
    }
    
    override suspend fun resetPasswordWithRecoveryCode(
        phone: String,
        recoveryCode: String,
        newPassword: String
    ): Result<Unit> {
        return try {
            val user = parentUserDao.findByPhone(phone)
                ?: return Result.failure(Exception("User not found"))
            
            // For now, recovery code verification is simplified
            // In production, you'd hash and compare recovery codes
            
            val newSalt = passwordHasher.generateSalt()
            val newHash = passwordHasher.hashPassword(newPassword, newSalt)
            
            parentUserDao.updatePassword(user.id, newSalt, newHash)
            
            Result.success(Unit)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
    
    override suspend fun enableBiometric(encryptedPassword: String): Result<Unit> {
        // TODO: Implement biometric enable logic
        return Result.success(Unit)
    }
    
    override suspend fun isBiometricEnabled(): Boolean {
        // TODO: Implement biometric check
        return false
    }
    
    override suspend fun loginWithBiometric(decryptedPassword: String): Result<ParentUser> {
        // TODO: Implement biometric login
        val userId = currentUserId ?: return Result.failure(Exception("Not logged in"))
        val user = parentUserDao.findById(userId)
            ?: return Result.failure(Exception("User not found"))
        return Result.success(user.toDomain())
    }
}
